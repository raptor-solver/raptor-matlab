function [rho, p] = computeAtmosphericQuantities(inputData)
% function that computes the density for the ascent problem

global modelChoices
if modelChoices.atmosphere == "exponential"
    [rho, p] = exponentialModel(inputData);
elseif modelChoices.atmosphere == "us76"
    [rho, p] = us76Model(inputData);
end

end

%% HELPER FUNCTIONS
function [rho, p] = exponentialModel(inputData)
% exponential model with the specified parameters

% preamble
r = inputData.states(1 : 3, :);
rho0 = inputData.auxdata.rho0;
p0 = inputData.auxdata.p0;
Hr = inputData.auxdata.Hr;
R0 = inputData.auxdata.R0;

% compute density
h = vecnorm(r) - R0;
rho = rho0 * exp(- h / Hr);
p = p0 * exp(- h / Hr);
end

function [rho, p] = us76Model(inputData)
% us76 model from tabulated data

% preamble
r = inputData.states(1 : 3, :);
R0 = inputData.auxdata.R0;
data = US76_atmosphere;

% compute density
h = vecnorm(r) - R0;
h (h < 0) = 0; h(h > 200000) = 200000;
rho = interp1(data(:, 4)', data(:, 1)', h'/1000)';
p = interp1(data(:, 4)', data(:, 2)', h'/1000)';
end

