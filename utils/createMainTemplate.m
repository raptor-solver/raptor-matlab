function createMainTemplate()
%CREATEMAINTEMPLATE Create a generic RAPTOR main.m skeleton.
%
%   CREATEMAINTEMPLATE() creates a script named "main.m" in the current
%   working directory containing a standardized skeleton for defining and
%   solving a RAPTOR optimal control problem.
%
%   Inputs:
%       None.
%
%   Outputs:
%       None. A file named "main.m" is created in the current folder.
%
%   Usage:
%       createMainTemplate()
%
%   Behavior:
%       - If a file named "main.m" already exists in the current folder,
%         the function throws an error and does NOT overwrite it.
%       - The generated script is divided into two main sections:
%             %% Problem Definition %% Problem Solution
%
%   Description:
%       The generated script provides a consistent and ordered structure
%       for RAPTOR problem definitions. All problem-specific elements must
%       be completed by the user.

filePath = fullfile(pwd, 'main.m');

% Do NOT overwrite existing file
if exist(filePath, 'file')
    error('createMainTemplate:FileExists', ...
        'A file named "main.m" already exists in this directory.');
end

fid = fopen(filePath, 'w');
if fid == -1
    error('createMainTemplate:FileError', ...
        'Could not create main.m in the current directory.');
end

% ---------------------------------------------------------------------
% Header
% ---------------------------------------------------------------------
fprintf(fid, '%% =========================================================================\n');
fprintf(fid, '%% main.m\n');
fprintf(fid, '%% =========================================================================\n');
fprintf(fid, '%% This file was automatically generated by createMainTemplate().\n');
fprintf(fid, '%% Complete the placeholders to define your RAPTOR problem.\n');
fprintf(fid, '%% =========================================================================\n\n');


fprintf(fid, 'clearvars\n');
fprintf(fid, 'close all\n');
fprintf(fid, 'clc\n\n');

fprintf(fid, '%% Constants\n');
fprintf(fid, 'aux = []; %% <-- define problem constants here\n\n');

fprintf(fid, '%% =========================================================================\n');
fprintf(fid, '%%%% Problem Definition\n');
fprintf(fid, '%% =========================================================================\n\n');

fprintf(fid, '%% Start build timer\n');
fprintf(fid, 'tic\n\n');

fprintf(fid, '%% Instantiate OCP\n');
fprintf(fid, 'ocp = raptor.api.v1.OptimalControlProblem("ProblemName", aux, 0);\n\n');

fprintf(fid, '%% Add phase\n');
fprintf(fid, '%% phase = ocp.addPhase("Phase1", nStates, nControls, nParameters);\n\n');

fprintf(fid, '%% ---------------------- Metadata -----------------------------------------\n');
fprintf(fid, '%% phase.metadata.name.time = "time";\n');
fprintf(fid, '%% phase.metadata.unit.time = "s";\n');
fprintf(fid, '%% phase.metadata.label.time = "t";\n');
fprintf(fid, '%% phase.metadata.label.states = [...];\n\n');

fprintf(fid, '%% ---------------------- Dynamics -----------------------------------------\n');
fprintf(fid, '%% dyn = phase.dynamics.add(@myDynamics);\n\n');

fprintf(fid, '%% ------------------- Path Constraints ------------------------------------\n');
fprintf(fid, '%% phase.constraints.path.stack("c1", lower, upper);\n');
fprintf(fid, '%% phase.constraints.path.c1.label = "c1";\n');
fprintf(fid, '%% phase.constraints.path.c1.unit = "-";\n');
fprintf(fid, '%% f = phase.constraints.path.c1.add(@myPathConstraint);\n');
fprintf(fid, '%% f.functionType = "nonlinear";\n\n');

fprintf(fid, '%% ------------------- Boundary Constraints --------------------------------\n');
fprintf(fid, '%% phase.constraints.boundary.stack("c1", lower, upper);\n');
fprintf(fid, '%% f = phase.constraints.boundary.c1.add(@myBoundaryConstraint);\n');
fprintf(fid, '%% f.functionType = "nonlinear";\n\n');

fprintf(fid, '%% ------------------------- Costs -----------------------------------------\n');
fprintf(fid, '%% Lagrange term\n');
fprintf(fid, '%% f = phase.costs.lagrange.add(@myLagrangeCost);\n');
fprintf(fid, '%% f.functionType = "nonlinear";\n\n');

fprintf(fid, '%% Mayer term\n');
fprintf(fid, '%% f = phase.costs.mayer.add(@myMayerCost);\n');
fprintf(fid, '%% f.functionType = "linear";\n\n');

fprintf(fid, '%% ------------------ Boundary Conditions ----------------------------------\n');
fprintf(fid, '%% phase.boundaryConditions.initial.time = [];\n');
fprintf(fid, '%% phase.boundaryConditions.initial.states = [];\n');
fprintf(fid, '%% phase.boundaryConditions.final.time = [];\n');
fprintf(fid, '%% phase.boundaryConditions.final.states(1 : end - 1) = [];\n\n');

fprintf(fid, '%% ---------------------- Initial Guess ------------------------------------\n');
fprintf(fid, '%% phase.initialGuess.final.states(end) = [];\n');
fprintf(fid, '%% phase.initialGuess.continuous.controls = [];\n');
fprintf(fid, '%% phase.initialGuess.linear();\n\n');

fprintf(fid, '%% ---------------------- Box Constraints ----------------------------------\n');
fprintf(fid, '%% phase.box.lower.states = [];\n');
fprintf(fid, '%% phase.box.upper.states = [];\n');
fprintf(fid, '%% phase.box.lower.controls = [];\n');
fprintf(fid, '%% phase.box.upper.controls = [];\n');
fprintf(fid, '%% phase.box.lower.finalTime = [];\n');
fprintf(fid, '%% phase.box.upper.finalTime = [];\n\n');

fprintf(fid, '%% ------------------- Collocation Settings --------------------------------\n');
fprintf(fid, '%% phase.collocation.interpolant = "Lagrange";\n');
fprintf(fid, '%% phase.collocation.polynomials = "Legendre";\n');
fprintf(fid, '%% phase.collocation.nodes = "flipped-Gauss-Radau";\n');
fprintf(fid, '%% phase.collocation.nNodes = 20;\n\n');

fprintf(fid, '%% Build problem\n');
fprintf(fid, 'problem = raptor.build(ocp);\n\n');

fprintf(fid, '%% Optional: solver configuration\n');
fprintf(fid, '%% problem.config.transcription.method = "NLP";\n');
fprintf(fid, '%% problem.config.scaling.method = "RuizStatic";\n');
fprintf(fid, '%% problem.config.scaling.settings.tol = 1e-5;\n');
fprintf(fid, '%% problem.config.solver.method = "Ipopt";\n');
fprintf(fid, '%% problem.config.solver.tol = 1e-6;\n');
fprintf(fid, '%% problem.config.postprocessing.validation.method = "RungeKutta45";\n');
fprintf(fid, '%% problem.config.postprocessing.plotting.dual = false;\n\n');

fprintf(fid, 'buildTime = toc;\n');
fprintf(fid, 'fprintf("RAPTOR build time: %%f\\n", buildTime);\n\n');

fprintf(fid, '%% =========================================================================\n');
fprintf(fid, '%%%% Problem Solution\n');
fprintf(fid, '%% =========================================================================\n');
fprintf(fid, 'sol = problem.solve();\n\n');

fclose(fid);

fprintf('RAPTOR main.m template successfully created in \n%s\n', pwd);
end