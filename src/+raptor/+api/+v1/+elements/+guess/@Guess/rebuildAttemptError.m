function rebuildAttemptError(obj)
% method that throws the error for a guess object that was already built
raptor.core.utils.Logger.err("guess:rebuildAttempt", strcat("The guess object for phase ", ...
    obj.phase.name, " has already been built, and information previously" + ...
    " stored inside it may have been overwritten.\n The available build" + ...
    " methods for the guess object are:\nlinear()\nfromControls()n" + ...
    "fromControlLaw()\nfromContinuous()\nThe guess object can only" + ...
    " be built once.\n"));
end

