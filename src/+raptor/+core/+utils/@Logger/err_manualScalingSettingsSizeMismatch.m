function err_manualScalingSettingsSizeMismatch(phaseIdx, settingsPropertyName, ...
    settingsPropertySize, truePropertySize)
% method that triggers an error for a manual scaling field that has a size
% mismatch with respect to the corresponding problem field
raptor.core.utils.Logger.err("scaling:manual", strcat( "Error in manual " + ...
    "scaling settings: phase ", string(phaseIdx), "\nvariable/constraint " + ...
    "", settingsPropertyName, " has size ", string(truePropertySize), ",\nwhile" + ...
    " the provided scales for such variables have size ", string(settingsPropertySize)));
end
