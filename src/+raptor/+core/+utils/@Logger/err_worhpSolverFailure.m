function err_worhpSolverFailure(ME, session)
% error reporting a failure raised by the WORHP mex gateway, adding the
% context that the gateway itself cannot provide. The message is passed as
% an argument rather than as a format, because it carries file paths that
% sprintf would read as escape sequences
hints = [ ...
    "the problem data rejected by WORHP (a variable or constraint with " + ...
    "crossed bounds, or a constraint with no finite bound at all)"; ...
    "an error raised by one of the raptor callbacks while evaluating the " + ...
    "objective, the constraints or their derivatives"; ...
    "an inconsistent warm start, when the problem size changed between solves"];
raptor.core.utils.Logger.warn("solver:Worhp", "%s", ...
    "The WORHP mex gateway failed while solving in '" + session.directory + "'." + ...
    newline + "The most common causes are:" + newline + "  - " + ...
    join(hints, newline + "  - "));
raptor.core.utils.Logger.err("solver:worhpSolverFailure", "%s", ...
    "WORHP failed during the solution process:" + newline + string(ME.message));
end
