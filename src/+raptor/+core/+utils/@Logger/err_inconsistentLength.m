function err_inconsistentLength(phaseName, varName1, varName2)
% generic error for two continuous variables with inconsistent length
raptor.core.utils.Logger.err("size:inconsistentLength", strcat("In phase '", ...
    phaseName, "', variables\n", varName1, "\n", varName2, ...
    "\n have inconsistent length: check for possible mismatches" + ...
    " their continuous time definition.\n"));
end

